// Copies agents/*.md and departments.json into tests/files.ts, so the tests
// (which run with no file system) check the team as it really is.
//   node scripts/fixture.mjs           write tests/files.ts
//   node scripts/fixture.mjs --check   exit 1 if tests/files.ts is out of date
// The plugin itself never reads tests/files.ts: it reads the real files at run time.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'tests', 'files.ts')
const files = { 'departments.json': readFileSync(join(root, 'departments.json'), 'utf8') }
for (const name of readdirSync(join(root, 'agents')).filter(n => n.endsWith('.md')).sort()) {
  files[`agents/${name}`] = readFileSync(join(root, 'agents', name), 'utf8')
}
const text = '// Generated by scripts/fixture.mjs from agents/*.md and departments.json: do not edit.\n' +
  '// After changing an agent file or departments.json, run: node scripts/fixture.mjs\n' +
  `export const FILES: Record<string, string> = ${JSON.stringify(files, null, 2)}\n`

if (process.argv.includes('--check')) {
  let now = ''
  try { now = readFileSync(out, 'utf8') } catch {}
  if (now.replace(/\r\n/g, '\n') !== text) {
    console.error('tests/files.ts is out of date: run node scripts/fixture.mjs')
    process.exit(1)
  }
  console.log(`tests/files.ts is up to date (${Object.keys(files).length} files)`)
} else {
  writeFileSync(out, text)
  console.log(`wrote tests/files.ts (${Object.keys(files).length} files)`)
}
